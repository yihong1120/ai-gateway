"""Validated user-instruction planning.

The planner has intentionally small authority: it turns the current user message
into a validated :class:`JobPlan`.  It never sees document text and never
performs file or network side effects.
"""
from __future__ import annotations

from typing import Any
from typing import Protocol
from typing import TypedDict

from official_document_workflow.domain.workflow import JobPlan
from official_document_workflow.domain.workflow import PendingReminderResolution


class ChatMessage(TypedDict):
    role: str
    content: str | list[ChatTextPart]


class ChatTextPart(TypedDict):
    type: str
    text: str


class ChatBody(TypedDict):
    messages: list[ChatMessage]


class InstructionPlanner(Protocol):
    """Port implemented by the Open WebUI/LiteLLM adapter."""

    async def __call__(self, current_user_message: str) -> dict[str, Any]: ...


class PendingReminderResolver(Protocol):
    """Port for resolving one server-created deadline-choice question."""

    async def __call__(
        self,
        current_user_message: str,
        deadline_options: tuple[str, ...],
    ) -> dict[str, Any]: ...


async def plan_current_instruction(
    current_user_message: str,
    planner: InstructionPlanner,
) -> JobPlan:
    """Plan exactly one current user message with no chat-history access.

    An empty message has a deterministic default plan and therefore does not
    incur a planning-model call.  Any non-empty message must receive a valid
    planner result; silently falling back would risk ignoring an instruction
    such as "do not create DOCX".
    """

    current_user_message = current_user_message.strip()
    if len(current_user_message) > 20_000:
        raise ValueError('本次指令超過 20000 字元')
    if not current_user_message:
        return JobPlan()
    raw_plan = await planner(current_user_message)
    return JobPlan.model_validate(raw_plan)


async def resolve_pending_reminder_choice(
    current_user_message: str,
    deadline_options: tuple[str, ...],
    resolver: PendingReminderResolver,
) -> PendingReminderResolution:
    """Resolve a reply only against supplied verified deadline indices.

    ``deadline_options`` is generated by the server from existing validated
    CSV rows.  The resolver may only choose an index from that list, all of
    it, or request another clarification; it cannot revise document facts or
    request another operation.
    """

    current_user_message = current_user_message.strip()
    if len(current_user_message) > 20_000:
        raise ValueError('本次指令超過 20000 字元')
    if not current_user_message:
        raise ValueError('請回覆要套用所有期限，或指定其中一項期限')
    if not deadline_options:
        raise ValueError('沒有可供選擇的已驗證期限')

    raw_resolution = await resolver(
        current_user_message, deadline_options,
    )

    resolution = PendingReminderResolution.model_validate(raw_resolution)
    if (
        resolution.decision == 'selected_verified_deadline'
        and resolution.selected_deadline_index is not None
        and resolution.selected_deadline_index >= len(deadline_options)
    ):
        raise ValueError('指定的期限不在本次可選範圍')
    return resolution


def current_user_message_from_body(body: ChatBody) -> str:
    """Return only the latest user text, never prior history or attachments.

    Open WebUI sends a full conversation in ``body``.  Taking the final user
    turn avoids allowing older instructions or old attachment references to
    affect a new document batch.
    """

    messages = body.get('messages', [])
    for item in reversed(messages):
        if item.get('role') != 'user':
            continue
        content = item['content']
        if type(content) is str:
            return content.strip()
        return '\n'.join(
            part['text'] for part in content
            if part['type'] in {'text', 'input_text'}
        ).strip()
    return ''
