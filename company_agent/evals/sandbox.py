"""Disposable evaluation schemas and synthetic state, independent of test cases."""
from __future__ import annotations

import os
import tempfile
import uuid
from contextlib import asynccontextmanager
from contextlib import contextmanager
from contextlib import ExitStack
from pathlib import Path

import psycopg
from langgraph.checkpoint.postgres.aio import AsyncPostgresSaver
from langgraph.checkpoint.serde.encrypted import EncryptedSerializer
from langgraph.checkpoint.serde.jsonplus import JsonPlusSerializer
from psycopg import sql

from examples.official_document_workflow.runtime import WorkflowResources
from examples.official_document_workflow.runtime import WorkflowSettings


def make_state_directory(path):
    path.mkdir(mode=0o700)
    for name in ('checkpoint.key', 'nas.key'):
        with (path / name).open('xb') as stream:
            os.fchmod(stream.fileno(), 0o600)
            stream.write(os.urandom(32))


@asynccontextmanager
async def checkpointer(store):
    serde = EncryptedSerializer.from_pycryptodome_aes(
        serde=JsonPlusSerializer(pickle_fallback=False, allowed_json_modules=[]),
        key=(store.directory / 'checkpoint.key').read_bytes(),
    )
    async with AsyncPostgresSaver.from_conn_string(store.conninfo, serde=serde) as saver:
        await saver.setup()
        yield saver


@contextmanager
def isolated_schemas(dsn):
    """Bind fresh schemas, then drop only the names generated by this context."""
    if not dsn:
        raise ValueError('An explicit PostgreSQL DSN is required for evaluation.')

    schema = 'company_agent_test_' + uuid.uuid4().hex
    workflow_schema = 'eip_agent_test_' + uuid.uuid4().hex
    updates = {'COMPANY_AGENT_DATABASE_URL': dsn, 'COMPANY_AGENT_DB_SCHEMA': schema}
    previous = {key: os.environ.get(key) for key in updates}

    def restore_environment():
        for key, value in previous.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value

    def drop(name):
        with psycopg.connect(dsn) as db:
            db.execute(sql.SQL('DROP SCHEMA IF EXISTS {} CASCADE').format(sql.Identifier(name)))

    with ExitStack() as stack:
        stack.callback(restore_environment)
        os.environ.update(updates)
        temporary = stack.enter_context(tempfile.TemporaryDirectory())
        stack.callback(drop, schema)
        stack.callback(drop, workflow_schema)
        resources = WorkflowResources(WorkflowSettings(dsn, workflow_schema, Path(temporary) / 'key'))
        stack.enter_context(resources.bind())
        yield
