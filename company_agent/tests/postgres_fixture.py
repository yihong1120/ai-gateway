"""Real PostgreSQL tests, each in a disposable randomly named schema."""
from __future__ import annotations

import os
import unittest
import uuid
from contextlib import asynccontextmanager
from unittest.mock import patch

import psycopg
from langgraph.checkpoint.postgres.aio import AsyncPostgresSaver
from langgraph.checkpoint.serde.encrypted import EncryptedSerializer
from langgraph.checkpoint.serde.jsonplus import JsonPlusSerializer
from psycopg import sql


def make_state_directory(path):
    path.mkdir(mode=0o700)
    for name in ('checkpoint.key', 'nas.key'):
        with (path / name).open('xb') as stream:
            os.fchmod(stream.fileno(), 0o600)
            stream.write(os.urandom(32))


@asynccontextmanager
async def checkpointer(store):
    """Open native checkpoints for test setup and assertions."""
    serde = EncryptedSerializer.from_pycryptodome_aes(
        serde=JsonPlusSerializer(pickle_fallback=False, allowed_json_modules=[]),
        key=(store.directory / 'checkpoint.key').read_bytes(),
    )
    async with AsyncPostgresSaver.from_conn_string(store.conninfo, serde=serde) as saver:
        await saver.setup()
        yield saver


class PostgreSQLTestCase(unittest.TestCase):
    def setUp(self):
        super().setUp()
        dsn = os.getenv('COMPANY_AGENT_TEST_DATABASE_URL')
        if not dsn:
            raise unittest.SkipTest('Set COMPANY_AGENT_TEST_DATABASE_URL for real PostgreSQL tests')
        schema = 'company_agent_test_'+uuid.uuid4().hex
        env = patch.dict(os.environ, {'COMPANY_AGENT_DATABASE_URL': dsn, 'COMPANY_AGENT_DB_SCHEMA': schema})
        env.start()
        self.addCleanup(env.stop)

        def cleanup():
            # Exact UUID generated by this fixture; never a user schema.
            assert schema.startswith('company_agent_test_') and len(schema) == 51
            with psycopg.connect(dsn) as db:
                db.execute(sql.SQL('DROP SCHEMA IF EXISTS {} CASCADE').format(sql.Identifier(schema)))
        self.addCleanup(cleanup)
