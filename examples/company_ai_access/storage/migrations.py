"""Versioned offline registry initialization, serialized per PostgreSQL schema."""
from __future__ import annotations

import hashlib
import os

import psycopg
from cryptography.fernet import Fernet
from psycopg import sql
from psycopg.conninfo import make_conninfo
from psycopg.rows import dict_row


def initialize(dsn, schema, key_path, *, legacy_import=False):
    legacy = key_path.parent / 'access.sqlite3'
    with psycopg.connect(make_conninfo(dsn, connect_timeout=5), row_factory=dict_row) as db:
        db.execute(
            'SELECT pg_advisory_xact_lock(hashtextextended(%s,0))',
            (schema + ':migration',),
        )
        db.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(sql.Identifier(schema)))
        db.execute(sql.SQL('SET LOCAL search_path TO {}').format(sql.Identifier(schema)))
        db.execute('CREATE TABLE IF NOT EXISTS schema_version (version INTEGER PRIMARY KEY)')
        versions = db.execute('SELECT version FROM schema_version').fetchall()
        if versions and versions != [{'version': 1}]:
            raise ValueError('Unsupported AI access schema version.')
        db.execute(
            'CREATE TABLE IF NOT EXISTS registry_metadata (id INTEGER PRIMARY KEY CHECK(id=1), key_hash TEXT NOT NULL, legacy_hash TEXT)',
        )
        metadata = db.execute('SELECT * FROM registry_metadata WHERE id=1').fetchone()
        if not key_path.exists():
            if metadata or legacy.exists():
                raise ValueError('Restore access.key; refusing to replace the existing registry key.')
            fd = os.open(key_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, 'wb') as stream:
                stream.write(Fernet.generate_key())
                stream.flush()
                os.fsync(stream.fileno())
        key = key_path.read_bytes()
        cipher = Fernet(key)
        fingerprint = hashlib.sha256(key).hexdigest()
        if metadata and metadata['key_hash'] != fingerprint:
            raise ValueError('access.key does not match the PostgreSQL registry.')
        if legacy.exists() and not legacy_import and not (metadata and metadata['legacy_hash']):
            raise ValueError(
                'Migrate access.sqlite3 with python -m examples.company_ai_access.cli.migrate before starting.',
            )
        db.execute(
            'INSERT INTO registry_metadata(id,key_hash) VALUES (1,%s) ON CONFLICT DO NOTHING',
            (fingerprint,),
        )
        db.execute(
            'CREATE TABLE IF NOT EXISTS records (kind TEXT NOT NULL,id TEXT NOT NULL,subject TEXT NOT NULL,data JSONB NOT NULL,PRIMARY KEY(kind,id))',
        )
        db.execute('CREATE INDEX IF NOT EXISTS owner ON records(kind,subject)')
        db.execute("CREATE UNIQUE INDEX IF NOT EXISTS device_hash ON records((data->>'key_hash')) WHERE kind='device'")
        db.execute(
            'CREATE TABLE IF NOT EXISTS audit (seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,at BIGINT NOT NULL,event TEXT NOT NULL,subject TEXT NOT NULL,device TEXT NOT NULL)',
        )
        db.execute(
            'CREATE TABLE IF NOT EXISTS limits (id TEXT PRIMARY KEY,count INTEGER NOT NULL,until BIGINT NOT NULL)',
        )
        db.execute('INSERT INTO schema_version VALUES (1) ON CONFLICT DO NOTHING')
    return cipher
